using System;
using System.Globalization;
using System.IO;
using Microsoft.AspNetCore.Hosting;
using ProjectManagement.Services.Presentation;

namespace ProjectManagement.Services.Analytics.Presentation;

// SECTION: The Analytics slide frame (one look for the CoE and ARPP decks)
/// <summary>
/// What every Analytics slide shares, so the CoE and ARPP decks downloaded from one page look like one
/// family (owner, 7 Nov 2026): the page margins and palette, the header (formation crest left, SDD insignia
/// right, title and subtitle over a navy rule, as the Briefing Studio decks), the footer ("Generated by
/// PRISM ERP on &lt;date&gt;" and the slide number), heading bars, stat cards and the text measure that
/// decides where a long list carries on.
/// </summary>
internal static class AnalyticsSlideFrame
{
    public const double SlideWidth = 13.333333;
    public const double SlideHeight = 7.5;
    public const double Left = .45;
    public const double Right = 12.88;
    public const double ContentWidth = Right - Left;
    public const double BodyTop = 1.32;
    public const double BodyBottom = 6.88;
    public const double HeadingHeight = .36;

    public const string Navy = "1F2A44";
    public const string Blue = "3B6FD8";
    public const string Green = "2E9152";
    public const string Orange = "D07A24";
    public const string Red = "C83B3B";
    public const string Ink = "1F2937";
    public const string Muted = "6B7280";
    public const string HeaderTint = "E9EEF6";
    public const string CardTint = "F1F4F8";
    public const string Rule = "E3E8EF";

    /// <summary>The two insignia, read once per deck; either may be missing.</summary>
    public sealed record Logos(byte[]? Left, byte[]? Right)
    {
        public static Logos From(LogoPaths paths) => new(Read(paths.Left), Read(paths.Right));

        private static byte[]? Read(string? path) =>
            string.IsNullOrWhiteSpace(path) || !File.Exists(path) ? null : File.ReadAllBytes(path);
    }

    /// <summary>Where the briefing decks' insignia live: the formation crest and the SDD insignia.</summary>
    public sealed record LogoPaths(string? Left, string? Right)
    {
        public static LogoPaths Find(IWebHostEnvironment environment)
        {
            var webRootPath = string.IsNullOrWhiteSpace(environment.WebRootPath)
                ? Path.Combine(environment.ContentRootPath, "wwwroot")
                : environment.WebRootPath;
            var left = Path.Combine(webRootPath, "img", "logos", "artrac.png");
            var right = Path.Combine(webRootPath, "img", "logos", "sdd.png");
            return new LogoPaths(File.Exists(left) ? left : null, File.Exists(right) ? right : null);
        }
    }

    /// <summary>The header: white page, crest, title and subtitle, SDD insignia, navy rule. Returns where the title area ends on the right.</summary>
    public static double AddHeader(PptxSlideCanvas canvas, Logos logos, string title, string subtitle)
    {
        canvas.AddRect(0, 0, SlideWidth, SlideHeight, "FFFFFF");

        var titleX = Left;
        if (logos.Left is { Length: > 0 })
        {
            canvas.AddImageContained(logos.Left, Left - .03, .27, .66, .66, "Formation insignia");
            titleX = Left + .78;
        }

        var titleRight = Right;
        if (logos.Right is { Length: > 0 })
        {
            // The SDD insignia is slender: a taller box balances it against the denser crest.
            canvas.AddImageContained(logos.Right, Right - .56, .2, .56, .8, "Division insignia");
            titleRight = Right - .7;
        }

        canvas.AddTextBox(
            titleX, .25, titleRight - titleX, .8,
            new[]
            {
                new PptxTextParagraph(new[] { new PptxRun(title, 22, Navy, true) }),
                new PptxTextParagraph(new[] { new PptxRun(subtitle, 11, Muted) }) { SpaceBeforePoints = 2 }
            },
            "Title",
            insets: new PptxInsets(.05, 0, .05, 0));
        canvas.AddLine(Left, 1.12, Right, 1.12, Navy, 1.25);
        return titleRight;
    }

    public static void AddFooter(PptxSlideCanvas canvas, DateOnly generatedOn, int number) =>
        canvas.AddTextBox(
            Right - 4, 7.0, 4, .26,
            new[]
            {
                new PptxTextParagraph(new[] { new PptxRun($"Generated by PRISM ERP on {Date(generatedOn)}     {number.ToString(CultureInfo.InvariantCulture)}", 9, Muted) }) { Align = "r" }
            },
            "Footer");

    /// <summary>A heading bar: its title, and the count at a right tab stop.</summary>
    public static void AddHeading(PptxSlideCanvas canvas, double x, double y, double width, string title, int count, string name, string fill = HeaderTint) =>
        canvas.AddTextBox(
            x, y, width, HeadingHeight,
            new[]
            {
                new PptxTextParagraph(new[] { new PptxRun(title, 12, Navy, true), new PptxRun("\t" + count.ToString(CultureInfo.InvariantCulture), 12, Navy, true) })
                {
                    RightTabAt = width - .12
                }
            },
            name,
            fill: fill,
            anchor: "ctr",
            insets: new PptxInsets(.06, 0, .06, 0));

    /// <summary>A stat card: its accent bar, then one shape holding the figure, the label and the line beneath.</summary>
    public static void AddCard(
        PptxSlideCanvas canvas,
        double x,
        double y,
        double width,
        double height,
        string figure,
        string label,
        string line,
        string accent,
        double figureSize = 34,
        double labelSize = 13,
        double lineSize = 11)
    {
        canvas.AddRect(x, y, .06, height, accent);
        canvas.AddTextBox(
            x + .06, y, width - .06, height,
            new[]
            {
                new PptxTextParagraph(new[] { new PptxRun(figure, figureSize, Navy, true) }),
                new PptxTextParagraph(new[] { new PptxRun(label, labelSize, Ink, true) }),
                new PptxTextParagraph(new[] { new PptxRun(line, lineSize, Muted) }) { SpaceBeforePoints = 2 }
            },
            $"{label} card",
            fill: CardTint,
            insets: new PptxInsets(.16, .08, .08, .06));
    }

    public static string Date(DateOnly date) => date.ToString("d MMM yyyy", CultureInfo.InvariantCulture);

    /// <summary>A tag ("Oct 2026", "Not known") never splits across lines.</summary>
    public static string NoBreak(string text) => text.Replace(' ', ' ');

    // SECTION: Text measuring (an estimate; generous, so a list carries on before PowerPoint must shrink it)
    // Average Aptos character width as a share of the font size, a little generous.
    public const double CharacterWidthEm = .5;

    public static double TextWidth(string text, double fontSize) =>
        (text ?? string.Empty).Length * fontSize * CharacterWidthEm / 72;

    /// <summary>Lines the text takes when wrapped at word breaks inside the width (a word too long for a line breaks).</summary>
    public static int LineCount(string text, double widthInches, double fontSize)
    {
        var capacity = Math.Max(1, (int)(widthInches * 72 / (fontSize * CharacterWidthEm)));
        var lines = 1;
        var used = 0;
        foreach (var word in (text ?? string.Empty).Split(' ', StringSplitOptions.RemoveEmptyEntries))
        {
            var length = word.Length;
            if (used == 0)
            {
                used = length;
            }
            else if (used + 1 + length <= capacity)
            {
                used += 1 + length;
            }
            else
            {
                lines++;
                used = length;
            }

            while (used > capacity)
            {
                lines++;
                used -= capacity;
            }
        }

        return lines;
    }
    // END SECTION
}
// END SECTION
