    [Fact]
    public void Compose_CardsChartColumnsAndANotKnownSlide()
    {
        var (content, slideCount) = CreateComposer().Compose(Sample(), Today);

        Assert.Equal(3, slideCount);
        var slides = SlideTexts(content);
        Assert.Equal(3, slides.Count);

        // Slide 1: the title, the five cards (the supply-order card reads as the column it feeds) and the chart.
        Assert.Contains("ARPP FY 2026-27: progress as of 6 Nov 2026", slides[0]);
        Assert.Contains("8 listed projects", slides[0]); // nine listed, one cancelled
        Assert.Contains("Under development", slides[0]);
        Assert.Contains("AoN to SO", slides[0]);
        Assert.Contains("Pre-AoN", slides[0]);
        Assert.Contains("TEC", slides[0]);
        Assert.Contains("DCD Projects 2", slides[0]); // legend with counts, only categories present
        Assert.DoesNotContain("Other R&D Projects", slides[0]);

        // Slide 2: the columns, full names, the PDC (red when overdue) without a stage tag, completion month and year.
        Assert.Contains("ARPP FY 2026-27: where each project stands", slides[1]);
        Assert.Contains("Under development", slides[1]);
        Assert.Contains("VR based Physiological Response Evaluation System (Stress Detection Simulator)", slides[1]);
        Assert.Contains("PDC 22 Jun 2026 · overdue", slides[1]);
        Assert.Contains("PDC 20 Feb 2027", slides[1]);
        Assert.Contains("Jan 2026", slides[1]); // kept on one line
        Assert.Contains("8 listed projects by where they stand, as of 6 Nov 2026 · 1 not known: slide 3", slides[1]);
        Assert.Contains("DCD Projects", slides[1]); // the legend in the header
        Assert.Contains("Generated by PRISM ERP on 6 Nov 2026", slides[1]);

        // Slide 3: the not-known projects, counted.
        Assert.Contains("ARPP FY 2026-27: not known as of 6 Nov 2026", slides[2]);
        Assert.Contains("NIRBHAY", slides[2]);

        // Cancelled projects are counted nowhere on the slides; the presenter's notes of slide 2 name them.
        Assert.All(slides, text => Assert.DoesNotContain("SAKO", text));
        Assert.All(slides, text => Assert.DoesNotContain("ancelled", text));
        var notes = NotesTexts(content);
        Assert.Null(notes[0]);
        Assert.Contains("VR based SAKO Sniper Sml", notes[1]);
        Assert.Null(notes[2]);
    }

    [Fact]
    public void Compose_EachColumnIsOneTextBox_EachProjectOneParagraph()
    {
        var (content, _) = CreateComposer().Compose(Sample(), Today);

        using var stream = new MemoryStream(content);
        using var document = PresentationDocument.Open(stream, false);
        var part = document.PresentationPart!;
        var slide = (SlidePart)part.GetPartById(part.Presentation.SlideIdList!.Elements<DocumentFormat.OpenXml.Presentation.SlideId>().ElementAt(1).RelationshipId!.Value!);
        var shapes = slide.Slide.Descendants<DocumentFormat.OpenXml.Presentation.Shape>().ToList();

        // Title, legend, four headings, four columns of projects and the footer; no shape per project.
        Assert.True(shapes.Count <= 12, $"{shapes.Count} shapes on slide 2");
        var development = shapes.Single(shape => shape.NonVisualShapeProperties!.NonVisualDrawingProperties!.Name == "Under development projects");
        var paragraphs = development.Descendants<A.Paragraph>().ToList();
        Assert.Equal(3, paragraphs.Count);
        Assert.Contains(paragraphs, paragraph => paragraph.InnerText.Contains("Wpn Trg Sml (Tavor Rifle)") && paragraph.InnerText.Contains("PDC 22 Jun 2026"));
    }

    [Fact]
    public void Compose_AColumnThatDoesNotFit_ContinuesOnAThirdSlide()
    {
        var many = Enumerable.Range(1, 20)
            .Select(index => Line(index, $"Pre-AoN project number {index} with a fairly long name to wrap", "CoE", ArppProgressBucket.PreAon, StageCodes.AON))
            .ToList();
        var arpp = new ArppAnalyticsVm
        {
            FinancialYearStart = 2026,
            FinancialYearDisplay = "2026-27",
            ListedCount = many.Count,
            ProjectLines = many,
            ByStageByCategory = new[] { new OngoingStageByParentCategoryPoint(StageCodes.AON, "Acceptance of Necessity", "CoE", many.Count) },
            StageCategoryOrder = new[] { "CoE" }
        };

        var (content, slideCount) = CreateComposer().Compose(arpp, Today);

        Assert.Equal(3, slideCount);
        var slides = SlideTexts(content);
        Assert.Contains("ARPP FY 2026-27: where each project stands (continued)", slides[2]);
        Assert.Contains("Pre-AoN (cont.)", slides[2]);
        Assert.Contains("Pre-AoN project number 20 with a fairly long name to wrap", string.Join(" ", slides.Skip(1)));
    }

    [Fact]
    public void Compose_ManyCancelled_OnlyInTheNotes_NotKnownOnTheirOwnSlide()
    {
        var arpp = Sample();
        var extra = Enumerable.Range(100, 12)
            .Select(index => Line(index, $"Cancelled project number {index} with a long descriptive name", "CoE", ArppProgressBucket.Cancelled, null))
            .Concat(new[] { Line(200, "Project whose position cannot be told", "CoE", ArppProgressBucket.NotKnown, null) });
        arpp = new ArppAnalyticsVm
        {
            FinancialYearStart = arpp.FinancialYearStart,
            FinancialYearDisplay = arpp.FinancialYearDisplay,
            ListedCount = arpp.ListedCount + 13,
            ListedExcludingCancelled = new ArppListingVm(arpp.ListedExcludingCancelled.Count + 1, 0m, 0, 0, 0),
            ProjectLines = arpp.ProjectLines.Concat(extra).ToList(),
            ByStageByCategory = arpp.ByStageByCategory,
            StageCategoryOrder = arpp.StageCategoryOrder
        };

        var (content, slideCount) = CreateComposer().Compose(arpp, Today);

        Assert.Equal(3, slideCount);
        var slides = SlideTexts(content);
        Assert.Contains("ARPP FY 2026-27: not known as of 6 Nov 2026", slides[2]);
        Assert.Contains("2 listed projects whose position as of 6 Nov 2026 the records cannot tell", slides[2]);
        Assert.Contains("Project whose position cannot be told", slides[2]);
        Assert.All(slides, text => Assert.DoesNotContain("Cancelled project number", text));
        var notes = NotesTexts(content);
        Assert.Contains("Cancelled, not counted on these slides (13):", notes[1]);
        Assert.Contains("Cancelled project number 111 with a long descriptive name", notes[1]);
    }

