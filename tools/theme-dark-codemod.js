// White (or near-white) text, as used on solid fills.
const LIGHT_TEXT = /^(#fff(fff)?|white|var\(--(pm-text-inverted|bs-white)[^)]*\)|rgba?\(255,\s*255,\s*255(,\s*(0?\.(8[5-9]|9\d*)|1))?\))(\s*!\s*important)?$/i;

