const DARK = {
  page: '#0e0f11', card: '#16181b', tile: '#1e2125', raised: '#25282d',
  hairline: '#2c3035', strong: '#3a3f45', text: '#e6e8eb', strongText: '#f0f2f4',
  secondary: '#b4b9bf', muted: '#9aa0a6', faint: '#8a9097',
};

// Named white/black count too (color-mix(in srgb, x 10%, white) is common); other names are rare.
const LITERAL = /#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?)\([^()]*\)|(?<![\w-])(?:white|black)(?![\w-])/gi; // named colours are case-insensitive (White, BLACK)

// ---------- colour maths ----------
function parseColour(text) {
  if (/^white$/i.test(text)) return { r: 255, g: 255, b: 255, a: 1 };
  if (/^black$/i.test(text)) return { r: 0, g: 0, b: 0, a: 1 };
  let m = text.match(/^#([0-9a-f]{3,8})$/i);
  if (m) {
    let hex = m[1];
    if (hex.length === 3 || hex.length === 4) hex = [...hex].map((c) => c + c).join('');
    if (hex.length !== 6 && hex.length !== 8) return null;
    return {
      r: parseInt(hex.slice(0, 2), 16), g: parseInt(hex.slice(2, 4), 16), b: parseInt(hex.slice(4, 6), 16),
      a: hex.length === 8 ? parseInt(hex.slice(6, 8), 16) / 255 : 1,
    };
  }
  m = text.match(/^rgba?\(([^()]*)\)$/i);
  if (m) {
    const p = m[1].split(/[\s,/]+/).filter(Boolean);
    if (p.length < 3 || p.some((v) => !/^[\d.]+%?$/.test(v))) return null;
    const channel = (v) => (v.endsWith('%') ? (parseFloat(v) * 255) / 100 : parseFloat(v));
    const alpha = p[3] === undefined ? 1 : p[3].endsWith('%') ? parseFloat(p[3]) / 100 : parseFloat(p[3]);
    return { r: channel(p[0]), g: channel(p[1]), b: channel(p[2]), a: alpha };
  }
  return null; // hsl() and anything with var() are left alone
}

function toHsl({ r, g, b }) {
  const [rn, gn, bn] = [r / 255, g / 255, b / 255];
  const max = Math.max(rn, gn, bn);
  const min = Math.min(rn, gn, bn);
  const l = (max + min) / 2;
  if (max === min) return { h: 0, s: 0, l, chroma: 0 };
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  let h;
  if (max === rn) h = (gn - bn) / d + (gn < bn ? 6 : 0);
  else if (max === gn) h = (bn - rn) / d + 2;
  else h = (rn - gn) / d + 4;
  return { h: h * 60, s, l, chroma: d };
}

function fromHsl(h, s, l) {
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  const hex = (v) => Math.round(v * 255).toString(16).padStart(2, '0');
  return `#${hex(f(0))}${hex(f(8))}${hex(f(4))}`;
}

// The same hue, light enough to read on the dark card (like #6ea8fe for blue).
// Status and accent hues snap to the palette, so the same meaning gets the same colour.
function lifted(hsl) {
  const h = hsl.h;
  if (hsl.s >= 0.35) {
    if (h >= 205 && h < 245) return '#6ea8fe'; // accent blue
    if (h >= 95 && h < 160) return '#4ade80'; // good
    if (h >= 30 && h < 55) return '#fbbf24'; // attention
    if (h >= 345 || h < 12) return '#f87171'; // alert
  }
  return fromHsl(h, Math.min(Math.max(hsl.s, 0.6), 0.9), 0.7);
}

const round = (v) => Math.round(v * 100) / 100;

function relativeLuminance(hex) {
  const c = parseColour(hex);
  const f = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); };
  return 0.2126 * f(c.r) + 0.7152 * f(c.g) + 0.0722 * f(c.b);
}

// For accent tokens used both as a fill behind white text and as a text colour on the card:
// the same hue at relative luminance ~0.2 keeps about 4:1 contrast both ways.
function balanced(hsl) {
  const sat = Math.min(Math.max(hsl.s, 0.5), 0.75);
  let lo = 0.2;
  let hi = 0.8;
  for (let i = 0; i < 20; i++) {
    const mid = (lo + hi) / 2;
    if (relativeLuminance(fromHsl(hsl.h, sat, mid)) < 0.2) lo = mid; else hi = mid;
  }
  return fromHsl(hsl.h, sat, (lo + hi) / 2);
}

function roleOf(property, colour) {
  const p = property.toLowerCase();
  if (p.startsWith('--')) {
    if (/shadow/.test(p)) return 'shadow';
    if (/border|line|divider|outline|ring|stroke/.test(p)) return 'border';
    if (/bg|background|surface|card|fill|panel|track|tint|soft|wash|base|canvas|row|stripe|hover/.test(p)) return 'background';
    if (/text|ink|fg|color|muted|label|title|heading/.test(p)) return 'text';
    if (/accent|primary|secondary|success|warning|danger|info|brand|tone|status|good|fair|poor|red|green|blue|amber|teal|indigo|purple|orange|violet|cyan/.test(p)) return 'accent';
    if (colour) {
      const hsl = toHsl(colour);
      // An unnamed saturated colour token (--pi-navy, --brand) is usually a fill and a text colour.
      if (hsl.s >= 0.35 && hsl.chroma >= 0.2 && hsl.l < 0.6) return 'accent';
      return hsl.l > 0.6 ? 'background' : 'text';
    }
    return 'text';
  }
  if (p.includes('shadow')) return 'shadow';
  if (p.startsWith('border') || p.startsWith('outline') || p === 'column-rule' || p === 'column-rule-color') return 'border';
  if (p.startsWith('background')) return 'background';
  if (p === 'fill') return colour && toHsl(colour).l > 0.6 ? 'background' : 'text';
  return 'text'; // color, stroke, caret-color, text-decoration-color, accent-color, ...
}

// A page canvas (body, main, page shells, --x-bg / --x-page tokens) sits below the cards.
const PAGE = /(^|[\s,>])(body|main)\b|page|shell|canvas|-main\b|layout|backdrop/;
const PAGE_TOKEN = /^--[\w-]*-(bg|page|canvas|app-bg|page-bg)$/;

function darkColour(text, role, context = '', hint = {}) {
  const c = parseColour(text);
  if (!c) return text;
  const hsl = toHsl(c);
  // Greys and slates (including blue-grey borders like #dbe4f0) are neutral; pastel tints
  // like #edf3ff are not. Slate and navy text is neutral too: it becomes off-white or grey,
  // while text with a real hue (links, teal, green) is lifted.
  let neutral = hsl.chroma < 0.04 || (hsl.s < 0.5 && hsl.chroma < 0.12);
  if (role === 'text' && (hsl.s < 0.3 || (hsl.l < 0.35 && hsl.chroma < 0.22))) neutral = true;
  // Desaturated slates (disabled fills like #aebbd0) are greys for surfaces and borders too.
  if ((role === 'background' || role === 'border') && hsl.s < 0.5 && hsl.chroma < 0.2) neutral = true;

  if (c.a < 1 && role === 'accent') role = 'background';
  if (c.a < 1) {
    if (role === 'shadow') {
      if (!neutral && /(^|[\s,])0 0 0 \d/.test(context)) {
        const ring = parseColour(lifted(hsl)); // focus rings keep their accent
        return `rgba(${ring.r}, ${ring.g}, ${ring.b}, ${round(Math.min(Math.max(c.a * 1.5, 0.25), 0.45))})`;
      }
      return neutral && hsl.l > 0.85 ? `rgba(255, 255, 255, ${round(Math.min(c.a, 0.05))})` : `rgba(0, 0, 0, ${round(Math.min(0.6, c.a * 2.5 + 0.1))})`;
    }
    if (neutral) {
      if (hsl.l < 0.5) {
        // A dense dark fill is a scrim or overlay pill (on maps, photos): it stays dark.
        if (role === 'background' && c.a >= 0.5) return `rgba(0, 0, 0, ${round(Math.max(c.a, 0.72))})`;
        // A light dark veil (hover fill, hairline) on light becomes a light veil on dark.
        if (role === 'text') return `rgba(230, 232, 235, ${round(Math.max(c.a, 0.6))})`;
        if (role === 'border') return `rgba(255, 255, 255, ${round(Math.min(Math.max(c.a * 1.2, 0.08), 0.16))})`;
        return `rgba(255, 255, 255, ${round(Math.min(Math.max(c.a * 0.9, 0.03), 0.12))})`;
      }
      if (role === 'text') return text;
      if (role === 'border') return 'rgba(255, 255, 255, 0.08)';
      if (c.a >= 0.7) return `rgba(22, 24, 27, ${round(c.a)})`; // a frosted white panel is a card
      return `rgba(255, 255, 255, ${round(Math.min(c.a * 0.08, 0.06))})`;
    }
    const hue = parseColour(lifted(hsl));
    const alpha = role === 'background' ? round(Math.min(c.a * 1.4, 0.3)) : role === 'text' ? round(Math.max(c.a, 0.75)) : round(Math.min(c.a * 1.3, 0.45));
    return `rgba(${hue.r}, ${hue.g}, ${hue.b}, ${alpha})`;
  }

  if (role === 'shadow') return hsl.l < 0.5 ? 'rgba(0, 0, 0, 0.45)' : DARK.hairline;

  if (role === 'accent') {
    if (neutral) return darkColour(text, hsl.l > 0.6 ? 'background' : 'text', context, hint);
    if (hsl.l >= 0.8) return darkColour(text, 'background', context, hint); // a pale accent is a tint
    // Lifted for text (4.5:1+ on the card). Where it is a fill behind white text, convert()
    // deepens it again for that rule, so one colour never has to serve both.
    return lifted(hsl);
  }

  if (role === 'background') {
    // Only the selector's subject decides: '.x-page' is a canvas, '.x-page .tabs a' is not.
    const subjects = String(hint.selector || '').split(',').map((part) => part.trim().split(/\s*[>+~]\s*|\s+/).filter(Boolean).pop() || '');
    const isPage = PAGE_TOKEN.test(hint.property || '')
      || (!String(hint.property || '').startsWith('--') && subjects.every((subject) => subject && PAGE.test(` ${subject}`)));
    if (isPage && hsl.l >= 0.9 && hsl.l < 0.985 && hsl.chroma < 0.12) return DARK.page;
    if (neutral) {
      if (hsl.l >= 0.97) return DARK.card;
      if (hsl.l >= 0.93) return DARK.tile;
      if (hsl.l >= 0.86) return DARK.raised;
      if (hsl.l >= 0.6) return DARK.hairline;
      if (hsl.l < 0.35) return hsl.chroma > 0.08 ? DARK.raised : text; // navy panels become graphite; true greys stay
      return DARK.strong;
    }
    if (hsl.l >= 0.75) {
      const pct = Math.min(Math.max(Math.round((1 - hsl.l) * 120) + 4, 8), 30);
      return `color-mix(in srgb, ${lifted(hsl)} ${pct}%, ${DARK.card})`;
    }
    if (hsl.l < 0.3 && hsl.s <= 0.7) return DARK.raised; // navy/slate panels become graphite
    return text; // solid accent and status fills keep their colour
  }

  if (role === 'border') {
    if (neutral) {
      if (hsl.l >= 0.86) return DARK.hairline;
      if (hsl.l >= 0.6) return DARK.strong;
      return hsl.l < 0.3 ? DARK.strong : '#4a4f56';
    }
    if (hsl.l >= 0.75) return `color-mix(in srgb, ${lifted(hsl)} 30%, ${DARK.card})`;
    return lifted(hsl);
  }

  // text
  if (neutral) {
    if (hsl.l >= 0.8) return text; // light text (on dark or coloured fills) stays
    if (hsl.l < 0.15) return DARK.strongText;
    if (hsl.l < 0.3) return DARK.text;
    if (hsl.l < 0.45) return DARK.secondary;
    if (hsl.l < 0.62) return DARK.muted;
    return DARK.faint;
  }
  return hsl.l < 0.62 ? lifted(hsl) : text;
}

// ---------- rewriting ----------
function swapFor(property, literal) {
  const family = propertyFamily(property);
  const table = family === 'background' ? SWAPS.background
    : family === 'border' || family === 'outline' ? SWAPS.border
      : property.toLowerCase() === 'color' ? SWAPS.color : null;
  const token = table && table[literal.toLowerCase()];
  return token ? `var(${token}, ${literal})` : null;
}

function darkSelector(part) {
  if (/^:root\b/.test(part)) return part.replace(/^:root/, ':root[data-bs-theme="dark"]');
  if (/^html\b/.test(part)) return part.replace(/^html/, 'html[data-bs-theme="dark"]');
  // :where() keeps the light rule's specificity, so the dark rules follow the same cascade
  // (states and modifiers still win as they do in Light); being later in the file decides ties.
  return `:where([data-bs-theme="dark"]) ${part}`;
}

function convert(source) {
  const rules = readRules(source);
  // Existing dark rules: a declaration is already covered when a dark rule for the same
  // selector replaces that property, at the top level or in the same at-rule scope.
  const coverage = darkCoverage(rules);

  // Light islands (print proofs): a dark rule with color-scheme: light names classes whose
  // contents must keep Light's look. Rules for those classes, their BEM elements/modifiers and
  // their descendants get no generated dark rules.
  const islands = new Set();
  for (const rule of rules) {
    if (!isDarkSelector(rule.selector)) continue;
    if (!rule.declarations.some((d) => d.property === 'color-scheme' && /light/.test(d.value))) continue;
    for (const m of rule.selector.matchAll(/\.([\w-]+)/g)) islands.add(m[1]);
  }
  const inIsland = (part) => [...part.matchAll(/\.([\w-]+)/g)].some((m) => [...islands]
    .some((name) => m[1] === name || m[1].startsWith(`${name}__`) || m[1].startsWith(`${name}--`)));

  const edits = [];
  const blocks = new Map(); // at-rule chain -> [rule text]
  let swapped = 0;
  let generated = 0;
  let reasserted = 0;
  const hint = (rule, d) => ({ property: d.property, selector: rule.selector });
  const mapValue = (rule, d, value) => value.replace(LITERAL, (literal, offset) => (isProtected(value, offset)
    ? literal
    : darkColour(literal, roleOf(d.property, parseColour(literal)), value, hint(rule, d))));

  // Accent tokens are lifted for text in Dark (#6ea8fe-like, 4.5:1+ on the card), which is too
  // light behind white text. Find the tokens that end up lifted: site accents, this file's
  // literal accent tokens, and tokens that alias either.
  // Each token's Light value: its first definition outside any at-rule (the root/page value),
  // so a later component or media-query override never stands in for it.
  const defs = new Map();
  const defScoped = new Set();
  for (const rule of rules) {
    if (isDarkSelector(rule.selector)) continue;
    const scoped = rule.atRules.length > 0;
    for (const d of rule.declarations) {
      if (!d.property.startsWith('--')) continue;
      if (!defs.has(d.property) || (defScoped.has(d.property) && !scoped)) {
        defs.set(d.property, d.value);
        if (scoped) defScoped.add(d.property); else defScoped.delete(d.property);
      }
    }
  }
  const lifted = new Set();
  for (const [name, value] of defs) {
    const colour = parseColour(value.trim());
    if (colour && roleOf(name, colour) === 'accent' && darkColour(value.trim(), 'accent') !== value.trim()) lifted.add(name);
  }
  const refsLifted = (value) => [...value.matchAll(/var\(\s*(--[\w-]+)/g)].some((m) => SITE_LIFTED.test(m[1]) || lifted.has(m[1]));
  for (let changed = true; changed;) {
    changed = false;
    for (const [name, value] of defs) if (!lifted.has(name) && refsLifted(value)) { lifted.add(name); changed = true; }
  }
  const hasLightText = (rule) => rule.declarations.some((d) => d.property === 'color' && LIGHT_TEXT.test(d.value.trim()));
  // White text on an accent-token fill: the fill takes the same token mixed with black, which
  // keeps white text at 4.5:1 or better in Dark.
  const deepen = (value) => value.replace(/var\(\s*(--[\w-]+)\s*(?:,[^()]*(?:\([^()]*\)[^()]*)*)?\)/g,
    (match, name) => (SITE_LIFTED.test(name) || lifted.has(name) ? `color-mix(in srgb, ${match} 55%, #000)` : match));

  // Pass 1 finds the selectors that get a dark rule. Pass 2 emits them in source order, and
  // also re-asserts later state or modifier rules of those selectors (.x.active, .x:hover,
  // .x[aria-current]), which would otherwise lose to the dark base rule at equal specificity.
  const planned = new Set();
  const plannedFor = (family) => [...planned].filter((key) => key.endsWith(`|${family}`)).map((key) => key.slice(0, key.length - family.length - 1));
  for (const pass of [1, 2]) {
    for (const rule of rules) {
      if (isDarkSelector(rule.selector)) continue;
      if (rule.atRules.some((at) => /^@(keyframes|font-face|-webkit-keyframes|page)/.test(at) || /^@media[^{]*\b(print|prefers-color-scheme)\b/.test(at))) continue;
      // Island selectors are dropped from grouped rules (.proof, .card { ... }), so only the
      // ordinary selectors get a dark rule. The island's own colours are stated again in the
      // dark section, in source order, so a dark rule for a shared base class (.thumb) cannot
      // repaint a light island (.thumb--light) at equal specificity.
      const allParts = splitSelector(rule.selector);
      const islandParts = islands.size ? allParts.filter(inIsland) : [];
      if (pass === 2 && islandParts.length) {
        const keep = rule.declarations.filter((d) => COLOUR_FAMILIES.has(propertyFamily(d.property)) || d.property === 'background-image');
        if (keep.length) {
          const key = rule.atRules.join('\n');
          if (!blocks.has(key)) blocks.set(key, []);
          blocks.get(key).push(`${islandParts.map(darkSelector).join(',\n')} {\n${keep.map((d) => `    ${d.property}: ${d.value}${d.important ? ' !important' : ''};`).join('\n')}\n}`);
          reasserted += keep.length;
        }
      }
      const parts = allParts.filter((part) => !islandParts.includes(part));
      if (!parts.length) continue;
      const atKey = rule.atRules.join('|');
      const darkDeclarations = [];
      for (const d of rule.declarations) {
        const family = propertyFamily(d.property);
        const alreadyCovered = parts.every((part) => isCovered(coverage, part, d.property, d.value, atKey));
        const literals = [...d.value.matchAll(LITERAL)];

        if (pass === 2 && !alreadyCovered && COLOUR_FAMILIES.has(family)
          && !parts.some((part) => planned.has(`${part}|${family}`))
          && parts.some((part) => plannedFor(family).some((base) => compoundExtends(base, part)))) {
          // A state of a repainted selector: repeat it (mapped) after the base dark rule.
          const swappedValue = d.value.replace(LITERAL, (literal, offset) => (isProtected(d.value, offset) ? literal : swapFor(d.property, literal) || literal));
          darkDeclarations.push(`    ${d.property}: ${mapValue(rule, d, swappedValue)}${d.important ? ' !important' : ''};`);
          reasserted += 1;
        }
        if (pass === 2 && !alreadyCovered && (family === 'background' || family === 'border')
          && refsLifted(d.value) && hasLightText(rule)
          && !darkDeclarations.some((line) => line.startsWith(`    ${d.property}:`))) {
          darkDeclarations.push(`    ${d.property}: ${deepen(mapValue(rule, d, d.value))}${d.important ? ' !important' : ''};`);
          generated += 1;
          continue;
        }
        if (!literals.length) continue;

        // 1. Exact token swaps, in place.
        let remaining = 0;
        const value = d.value.replace(LITERAL, (literal, offset) => {
          if (isProtected(d.value, offset)) return literal;
          const swap = swapFor(d.property, literal);
          if (swap) {
            if (pass === 2) swapped += 1;
            return swap;
          }
          remaining += 1;
          return literal;
        });
        if (pass === 2 && value !== d.value) edits.push({ start: d.valueStart, end: d.valueEnd, text: rawWithValue(source, d, value) });
        if (!remaining || alreadyCovered) continue;

        // 2. A dark counterpart for what is left.
        const darkValue = mapValue(rule, d, value);
        if (darkValue === value) {
          // A colour kept on purpose (white text on a solid fill) is stated again in Dark, so a
          // repainted rule for another class on the same element cannot override it.
          if (pass === 2 && COLOUR_FAMILIES.has(family) && !darkDeclarations.some((line) => line.startsWith(`    ${d.property}:`))) {
            darkDeclarations.push(`    ${d.property}: ${value}${d.important ? ' !important' : ''};`);
            reasserted += 1;
          }
          continue;
        }
        if (pass === 1) {
          for (const part of parts) planned.add(`${part}|${family}`);
        } else if (!darkDeclarations.some((line) => line.startsWith(`    ${d.property}:`))) {
          darkDeclarations.push(`    ${d.property}: ${darkValue}${d.important ? ' !important' : ''};`);
          generated += 1;
        }
      }
      if (pass === 2 && darkDeclarations.length) {
        const key = rule.atRules.join('\n');
        if (!blocks.has(key)) blocks.set(key, []);
        blocks.get(key).push(`${parts.map(darkSelector).join(',\n')} {\n${darkDeclarations.join('\n')}\n}`);
      }
    }
  }

  // Light islands inherit custom properties from the page, and the page's tokens were just
  // redefined for Dark. Restore their Light values inside the islands.
  if (islands.size && blocks.has('')) {
    const redefined = new Set();
    for (const text of blocks.get('')) for (const m of text.matchAll(/^ {4}(--[\w-]+):/gm)) redefined.add(m[1]);
    const restore = [...redefined].filter((name) => defs.has(name)).sort().map((name) => `    ${name}: ${defs.get(name).trim()};`);
    if (restore.length) {
      blocks.get('').push(`/* Light islands keep the page's Light tokens. */\n:root[data-bs-theme="dark"] :is(${[...islands].map((name) => `.${name}`).join(', ')}) {\n${restore.join('\n')}\n}`);
    }
  }

  let output = source;
  for (const edit of edits.sort((a, b) => b.start - a.start)) {
    output = output.slice(0, edit.start) + edit.text + output.slice(edit.end);
  }
  if (blocks.size) {
    const eol = source.includes('\r\n') ? '\r\n' : '\n';
    const sections = [];
    for (const [chain, texts] of blocks) {
      let body = texts.join('\n\n');
      const ats = chain ? chain.split('\n') : [];
      for (const at of ats.slice().reverse()) body = `${at} {\n${indent(body)}\n}`;
      sections.push(body);
    }
    const header = `/* ============================================================\n   ${MARKER}.\n   Light is unchanged; these rules only apply under data-bs-theme="dark".\n   Palette: docs/ux/dark-theme-palette.md\n   ============================================================ */`;
    output = `${output.replace(/\s*$/, '')}\n\n${header}\n${sections.join('\n\n')}\n`.replace(/\r?\n/g, eol);
  }
  return { output, swapped, generated, reasserted };
}

