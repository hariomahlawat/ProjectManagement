const path = require('node:path');
const { readRules, isDarkSelector, splitSelector, lightSelectorOf, propertyFamily, darkCoverage, isCovered } = require('./lib/css-rules');

const MARKER = 'Dark theme (generated by tools/theme-dark-codemod.js, then reviewed)';

// Tokens whose light value is exactly this literal (verified against site.css :root).
