#!/usr/bin/env node
'use strict';

// Converts a stylesheet for the dark theme without changing Light:
//   1. Swaps a literal for a site token when the token's light value is identical
//      (background #fff -> var(--pm-card, #fff)), so the token flips in Dark by itself.
//   2. For every remaining literal in a light rule that no dark rule repaints yet, appends a
//      [data-bs-theme="dark"] rule with the same selector, mapping each colour by its role
//      (surface, text, border, shadow) onto the graphite palette in
//      docs/ux/dark-theme-palette.md. Saturated mid-tone fills (solid buttons, badges, status
//      bars) keep their colour; light tints become tints of the dark card.
// The output is a first pass: review the generated block and check the page in the browser.
//
// Usage: node tools/theme-dark-codemod.js <file.css>... [--dry-run]

